#!/usr/bin/env python3
"""Direct trace of g on the top reduced homology of Delta(OP(P) minus 0,1).

Second instrument for the LEFT side of eq. (characterconj) (mg-6bbe0).  It
does not use Moebius numbers, Lefschetz, or top-degree concentration:

    chi_H(g) := trace of g on  H_{n-3} = ker( d : C_{n-3} -> C_{n-4} )

where C_k is the simplicial chain group of the order complex of the proper
part of OP(P).  Since there are no (n-2)-simplices, H_{n-3} is exactly that
kernel.  Plain Python 3; written independently of poset_jks_check.py (own
enumeration of OP(P), own chains, own linear algebra).

Method.  g is a poset automorphism of OP(P), so it maps a chain
x_1 < ... < x_k to the chain gx_1 < ... < gx_k with the vertex order (hence
the orientation) preserved: g permutes oriented simplices with no signs.
Let m = ord(g) and take a prime p = 1 mod m, so F_p contains a primitive
m-th root omega.  For each k, the omega^k-eigenspace of g on C_{n-3} has
basis v_O = sum_{j<l} omega^{-kj} g^j c_O over the <g>-orbits O = {g^j c_O}
of length l with omega^{kl} = 1.  d commutes with g, so d v_O lies in the
omega^k-eigenspace of C_{n-4}, whose basis vectors u_{O'} have coefficient
1 at the orbit base c_{O'}; hence the matrix of d on that eigenspace has
entries (d v_O)[c_{O'}].  Its nullity N_k is the multiplicity of omega^k
on H_{n-3} (over F_p).

Passing to characteristic 0.  The matrices are reductions mod a prime of
Z[zeta_m] (zeta_m -> omega) of the corresponding matrices over Q(zeta_m),
so N_k(F_p) >= N_k(Q(zeta_m)) for every k.  Summing over k, if
sum_k N_k(F_p) equals dim_Q H_{n-3} then every N_k is exact.  We record the
total and compare it with e_C(P) (Jenca-Sarkoci: dim H_{n-3} = e_C(P)); we
also run two different primes.  The multiplicities must be constant on
Galois orbits (all k with the same gcd(k, m)); this is asserted.  Then

    trace(g | H_{n-3}) = sum_{d | m} mobius(d) * N_{k with gcd(k,m) = m/d}

because the primitive d-th roots of unity sum to mobius(d).

Run `python3 equivariant_homology.py --help`.
"""

import argparse
import itertools
import sys
import time
from collections import defaultdict

# ---------------------------------------------------------------------------
# OP(P): partitions whose blocks can be ordered compatibly with P (Kahn)


def partitions(n):
    """Set partitions of range(n) as sorted tuples of sorted tuples,
    generated by inserting element i into an existing block or a new one."""
    parts = [[]]
    for i in range(n):
        new = []
        for p in parts:
            for b in range(len(p)):
                new.append(p[:b] + [p[b] + [i]] + p[b + 1:])
            new.append(p + [[i]])
        parts = new
    return [tuple(tuple(b) for b in p) for p in parts]


def order_preserving(part, rel):
    """True iff the quotient digraph on blocks is acyclic (Kahn's algorithm)."""
    blk = {}
    for k, b in enumerate(part):
        for x in b:
            blk[x] = k
    out = defaultdict(set)
    indeg = [0] * len(part)
    for a, b in rel:
        A, B = blk[a], blk[b]
        if A != B and B not in out[A]:
            out[A].add(B)
            indeg[B] += 1
    queue = [k for k in range(len(part)) if indeg[k] == 0]
    seen = 0
    while queue:
        k = queue.pop()
        seen += 1
        for j in out[k]:
            indeg[j] -= 1
            if indeg[j] == 0:
                queue.append(j)
    return seen == len(part)


def canon(blocks):
    return tuple(sorted(tuple(sorted(b)) for b in blocks))


# ---------------------------------------------------------------------------
# Order complex of the proper part, top two chain groups


class Complex:
    def __init__(self, rel, n):
        self.n = n
        elems = [canon(p) for p in partitions(n) if order_preserving(p, rel)]
        self.proper = [e for e in elems if 2 <= len(e) <= n - 1]
        self.idx = {e: i for i, e in enumerate(self.proper)}
        self.opsize = len(elems)
        # upper covers inside OP: merge two blocks
        self.up = defaultdict(list)
        for e in self.proper:
            for i, j in itertools.combinations(range(len(e)), 2):
                f = canon([b for k, b in enumerate(e) if k not in (i, j)] + [e[i] + e[j]])
                if f in self.idx:
                    self.up[self.idx[e]].append(self.idx[f])
        # top chains: one element in each rank n-1, ..., 2 (finest first)
        self.top = []
        def ext(ch):
            if len(self.proper[ch[-1]]) == 2:
                self.top.append(tuple(ch))
                return
            for f in self.up[ch[-1]]:
                ext(ch + [f])
        if n >= 3:
            for e in self.proper:
                if len(e) == n - 1:
                    ext([self.idx[e]])

    def perm(self, g):
        """Index permutation of the proper part induced by g (g[x] = image)."""
        out = []
        for e in self.proper:
            out.append(self.idx[canon([[g[x] for x in b] for b in e])])
        return out


def orbits(chains, gp):
    """<g>-orbits of chains under the element permutation gp: list of
    (base, length) with base = the first chain met; plus chain -> (base, t)
    with chain = g^t base."""
    where, orbs = {}, []
    for c in chains:
        if c in where:
            continue
        x, t = c, 0
        while x not in where:
            where[x] = (c, t)
            x = tuple(gp[v] for v in x)
            t += 1
        assert x == c
        orbs.append((c, t))
    return orbs, where


# ---------------------------------------------------------------------------
# Sparse rank over F_p


def rank_mod_p(cols, p):
    pivots = {}
    r = 0
    for col in cols:
        col = {k: v % p for k, v in col.items() if v % p}
        while col:
            low = max(col)
            if low not in pivots:
                inv = pow(col[low], p - 2, p)
                pivots[low] = {k: v * inv % p for k, v in col.items()}
                r += 1
                break
            c = col[low]
            for k, v in pivots[low].items():
                w = (col.get(k, 0) - c * v) % p
                if w:
                    col[k] = w
                else:
                    col.pop(k, None)
    return r


# ---------------------------------------------------------------------------
# Number theory helpers


def is_prime(q):
    if q < 2:
        return False
    for d in range(2, int(q ** 0.5) + 1):
        if q % d == 0:
            return False
    return True


def prime_1_mod(m, start):
    """Smallest prime q >= start with q = 1 mod m."""
    q = start + (1 - start) % m
    while not is_prime(q):
        q += m
    return q


def primitive_root_of_unity(m, p):
    for a in range(2, p):
        w = pow(a, (p - 1) // m, p)
        if all(pow(w, m // q, p) != 1 for q in range(2, m + 1) if m % q == 0 and is_prime(q)):
            return w
    raise ValueError


def mobius(d):
    res, q = 1, 2
    while q * q <= d:
        if d % q == 0:
            d //= q
            if d % q == 0:
                return 0
            res = -res
        q += 1
    return -res if d > 1 else res


def perm_order(g):
    x, m, ident = tuple(g), 1, tuple(range(len(g)))
    while x != ident:
        x = tuple(g[i] for i in x)
        m += 1
    return m


# ---------------------------------------------------------------------------
# The trace


# Negative control only: True drops the last face d_{k} from the boundary.
# (Dropping the signs (-1)^i is NOT a valid control: every face of a top
# chain misses exactly one rank i, so rescaling faces by (-1)^i turns the
# signed top boundary into the unsigned one and the kernels coincide.)
CORRUPT = False


def eigen_multiplicities(cx, g, p):
    """N_k = dim ker(d | omega^k-eigenspace) over F_p, for k in Z/m."""
    m = perm_order(g)
    w = primitive_root_of_unity(m, p)
    gp = cx.perm(g)
    orbs, _ = orbits(cx.top, gp)
    faces = set()
    for c in cx.top:
        for i in range(len(c)):
            faces.add(c[:i] + c[i + 1:])
    _, fwhere = orbits(sorted(faces), gp)
    N = []
    for k in range(m):
        lam = pow(w, k, p)
        laminv = pow(lam, p - 2, p)
        cols = []
        for base, ell in orbs:
            if pow(lam, ell, p) != 1:
                continue
            col = defaultdict(int)
            x, coef = base, 1
            for j in range(ell):  # v = sum_j lam^{-j} g^j base
                for i in range(len(x) - (1 if CORRUPT else 0)):
                    f = x[:i] + x[i + 1:]
                    fb, t = fwhere[f]
                    if t == 0:  # coefficient of d v at an orbit base
                        col[fb] += coef * (-1 if i % 2 else 1)
                x = tuple(gp[v] for v in x)
                coef = coef * laminv % p
            cols.append(col)
        N.append(len(cols) - rank_mod_p(cols, p))
    return N


def trace_from_multiplicities(N):
    m = len(N)
    by_gcd = defaultdict(set)
    for k in range(m):
        by_gcd[gcd(k, m)].add(N[k])
    for gg, vals in by_gcd.items():
        assert len(vals) == 1, f"multiplicities not Galois-stable: {N}"
    # eigenvalues omega^k with gcd(k,m)=m/d are exactly the primitive d-th roots
    return sum(mobius(d) * next(iter(by_gcd[m // d])) for d in range(1, m + 1) if m % d == 0)


def gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def homology_trace(rel, n, g, primes=(0, 1), cx=None):
    """Returns dict with trace, multiplicities per prime, total dimension.
    One run per entry of `primes`: the successive primes p = 1 mod ord(g)
    above 10^6."""
    if cx is None:
        cx = Complex(rel, n)
    m = perm_order(g)
    out = {"m": m, "num_top": len(cx.top), "proper": len(cx.proper), "runs": []}
    start = 1_000_003
    for _ in primes:
        p = prime_1_mod(m, start)
        start = p + 1
        N = eigen_multiplicities(cx, g, p)
        out["runs"].append({"p": p, "N": N, "trace": trace_from_multiplicities(N),
                            "dim": sum(N)})
    assert len({r["p"] for r in out["runs"]}) == len(out["runs"]), "primes repeated"
    traces = {r["trace"] for r in out["runs"]}
    dims = {r["dim"] for r in out["runs"]}
    out["trace"] = traces.pop() if len(traces) == 1 else None
    out["dim"] = dims.pop() if len(dims) == 1 else None
    return out


def parse_cycles(s, n):
    """'(1 3 5)(2 4 6)' (1-based) -> permutation tuple, 0-based."""
    g = list(range(n))
    if s == "id":
        return tuple(g)
    for cyc in s.strip("()").split(")("):
        xs = [int(t) - 1 for t in cyc.split()]
        for a, b in zip(xs, xs[1:] + xs[:1]):
            g[a] = b
    return tuple(g)


def parse_covers(s):
    if s == "-":
        return []
    return [tuple(int(t) - 1 for t in c.split("<")) for c in s.split()]


def closure(pairs, n):
    rel = set(pairs)
    for k in range(n):
        for i in range(n):
            if (i, k) in rel:
                for j in range(n):
                    if (k, j) in rel:
                        rel.add((i, j))
    return frozenset(rel)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tsv", help="a character table written by poset_jks_check.py or n7_sweep.py")
    ap.add_argument("--select", choices=["discriminating", "nonzero", "nonidentity", "all"],
                    default="discriminating",
                    help="discriminating: rows where F1, F2 or F3 fails; nonzero: rows with "
                         "g != id and lhs != 0; nonidentity: all g != id")
    ap.add_argument("--n", type=int, help="only rows with this n")
    ap.add_argument("--max-top", type=int, default=10 ** 9,
                    help="skip posets whose order complex has more top simplices")
    ap.add_argument("--out", help="write a TSV of the results")
    ap.add_argument("--shard", default="0/1",
                    help="i/k: only posets whose position in the table is i mod k")
    ap.add_argument("--with-identity", action="store_true",
                    help="also compute g = id for each selected poset (dimension check)")
    a = ap.parse_args(argv)

    rows = []
    with open(a.tsv) as f:
        head = f.readline().rstrip("\n").split("\t")
        for line in f:
            rows.append(dict(zip(head, line.rstrip("\n").split("\t"))))
    if a.n:
        rows = [r for r in rows if int(r["n"]) == a.n]

    def wanted(r):
        if a.select == "all":
            return True
        if r["class_rep"] == "id":
            return False
        if a.select == "nonidentity":
            return True
        if a.select == "nonzero":
            return int(r["lhs"]) != 0
        return any(r[c] == "0" for c in ("F1_conj_ok", "F2_nosgn_ok", "F3_count_ok"))

    shard, nshard = map(int, a.shard.split("/"))
    order = {pid: k for k, pid in enumerate(dict.fromkeys(r["poset_id"] for r in rows))}
    rows = [r for r in rows if order[r["poset_id"]] % nshard == shard]
    sel = [r for r in rows if wanted(r)]
    if a.with_identity:
        ids = {r["poset_id"] for r in sel}
        sel = [r for r in rows if r["poset_id"] in ids and r["class_rep"] == "id"] + \
              [r for r in sel if r["class_rep"] != "id"]
    print(f"{len(sel)} (P, g) pairs selected from {a.tsv}")
    bad, skipped, results, cache = 0, 0, [], [None, None]
    for r in sel:
        n = int(r["n"])
        rel = closure(parse_covers(r["covers"]), n)
        g = parse_cycles(r["class_rep"], n)
        t = time.time()
        if cache[0] != r["poset_id"]:
            cache[:] = [r["poset_id"], Complex(rel, n)]
        if len(cache[1].top) > a.max_top:
            skipped += 1
            print(f"  SKIP {r['poset_id']} g={r['class_rep']}: {len(cache[1].top)} top simplices")
            continue
        h = homology_trace(rel, n, g, cx=cache[1])
        dt = time.time() - t
        lhs = int(r["lhs"])
        ok = h["trace"] == lhs
        dim_ok = h["dim"] == int(r["e_C"]) if r["class_rep"] == "id" else None
        bad += not ok
        line = (f"  {r['poset_id']} g={r['class_rep']} |OP|={r['num_OP']} "
                f"top simplices={h['num_top']} mult(p={h['runs'][0]['p']})="
                f"{h['runs'][0]['N']} trace_H={h['trace']} mu-side={lhs} "
                f"rhs={r['rhs']} {'AGREE' if ok else 'DISAGREE'} [{dt:.1f}s]")
        if dim_ok is not None:
            line += f" dim={h['dim']} e_C={r['e_C']} {'ok' if dim_ok else 'DIM MISMATCH'}"
            bad += not dim_ok
        print(line)
        sys.stdout.flush()
        results.append((r, h, ok, dt))
    print(f"disagreements: {bad}; skipped: {skipped}")
    if a.out:
        with open(a.out, "w") as f:
            f.write("\t".join(["poset_id", "n", "covers", "class_rep", "num_OP",
                               "top_simplices", "primes", "eigen_mult_by_k",
                               "trace_H", "lhs_mu", "rhs", "agree", "seconds"]) + "\n")
            for r, h, ok, dt in results:
                f.write("\t".join(map(str, [
                    r["poset_id"], r["n"], r["covers"], r["class_rep"], r["num_OP"],
                    h["num_top"], ",".join(str(x["p"]) for x in h["runs"]),
                    ",".join(map(str, h["runs"][0]["N"])), h["trace"], r["lhs"],
                    r["rhs"], int(ok), f"{dt:.2f}"])) + "\n")
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
