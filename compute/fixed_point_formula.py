# Braid positive control (type A_{n-1}): posets, OP(P), eq. closed


def set_partitions(s):
    s = list(s)
    if not s:
        yield []
        return
    first, rest = s[0], s[1:]
    for part in set_partitions(rest):
        for i in range(len(part)):
            yield part[:i] + [[first] + part[i]] + part[i + 1:]
        yield [[first]] + part


def is_order_preserving(rel, part):
    blk = {}
    for b, B in enumerate(part):
        for x in B:
            blk[x] = b
    m = len(part)
    adj = defaultdict(set)
    for a, b in rel:
        if blk[a] != blk[b]:
            adj[blk[a]].add(blk[b])
    # acyclic?
    state = [0] * m

    def dfs(u):
        state[u] = 1
        for v in adj[u]:
            if state[v] == 1:
                return False
            if state[v] == 0 and not dfs(v):
                return False
        state[u] = 2
        return True

    return all(state[u] or dfs(u) for u in range(m))


def mobius_number(o):
    m, k, res = o, 2, 1
    while k * k <= m:
        if m % k == 0:
            m //= k
            if m % k == 0:
                return 0
            res = -res
        k += 1
    if m > 1:
        res = -res
    return res


def lin_ext(elems, rel):
    out = []
    for w in itertools.permutations(elems):
        pos = {x: i for i, x in enumerate(w)}
        if all(pos[a] < pos[b] for a, b in rel if a in pos and b in pos):
            out.append(w)
    return out


def e_C(elems, rel):
    """Number of rotation classes of words meeting Lin(P|elems)."""
    rel = [(a, b) for a, b in rel if a in elems and b in elems]
    seen = set()
    cnt = 0
    for w in lin_ext(sorted(elems), rel):
        if w in seen:
            continue
        cnt += 1
        for j in range(len(w)):
            seen.add(w[j:] + w[:j])
    return cnt


def components(n, rel):
    par = list(range(n))

    def f(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x

    for a, b in rel:
        par[f(a)] = f(b)
    comp = defaultdict(set)
    for x in range(n):
        comp[f(x)].add(x)
    return [frozenset(c) for c in comp.values()]


_braid_cache = {}


def braid_check(arr, n, smax, ch, e, chi):
    """1 iff mu(Lambda^g) = mu(OP(P)^g) and eq. closed holds, for the poset
    P of the cone (i <_P j iff x_i < x_j on every chamber of V)."""
    M = e["M"]
    perm = [next(j for j in range(n) if M[j][i] == 1) for i in range(n)]  # g(i)
    c = ch[0]
    rel = []
    for idx, r in enumerate(arr.pos):
        if smax >> idx & 1:
            i = next(k for k in range(n) if r[k] == 1)
            j = next(k for k in range(n) if r[k] == -1)
            # chamber positive on e_i - e_j means x_i > x_j: j before i
            rel.append((j, i) if c >> idx & 1 else (i, j))
    rel = tuple(sorted(rel))
    k = (n, rel)
    if k not in _braid_cache:
        _braid_cache[k] = [pt for pt in set_partitions(range(n))
                           if is_order_preserving(rel, pt)]
    parts = _braid_cache[k]
    # mu(OP(P)^g): bottom = discrete partition, top = one block, refinement
    canon = lambda pt: frozenset(frozenset(B) for B in pt)
    fixed = []
    for pt in parts:
        cp = canon(pt)
        if frozenset(frozenset(perm[x] for x in B) for B in cp) == cp:
            fixed.append(cp)
    fixed.sort(key=lambda cp: -len(cp))
    mu = {}
    for y in fixed:
        if len(y) == n:
            mu[y] = 1
            continue
        s = 0
        for x, mx in mu.items():
            if x != y and all(any(B <= C for C in y) for B in x):
                s += mx
        mu[y] = -s
    mu_op = mu[next(y for y in fixed if len(y) == 1)]
    # eq. closed
    o = 1
    q = perm[:]
    while any(q[i] != i for i in range(n)):
        q = [perm[x] for x in q]
        o += 1
    lhs = e["det"] * (-1) ** (n - 3) * mu_op
    comps = components(n, rel)
    rhs = 0
    for pt in set_partitions(range(len(comps))):
        if len(pt) != o:
            continue
        blocks = [frozenset().union(*[comps[i] for i in B]) for B in pt]
        B0 = blocks[0]
        orbit = [B0]
        cur = B0
        for _ in range(o - 1):
            cur = frozenset(perm[x] for x in cur)
            orbit.append(cur)
        if set(orbit) != set(blocks) or frozenset(perm[x] for x in cur) != B0:
            continue
        rhs += e_C(B0, rel)
    rhs *= mobius_number(o)
    mu_lam = chi * e["det"] * (-1) ** arr.d
    return int(mu_lam == mu_op and lhs == rhs and lhs == chi
               and braid_cf(n, rel, perm, comps) == chi)


def braid_cf(n, rel, perm, comps):
    """Corollary CF-braid: sum over g-stable partitions sigma of the
    component set of mu_{Pi(K)^g}(sigma, top) times prod over <g>-orbits of
    blocks B of [stabiliser of B acts trivially on B] |Lin(P|_B)|."""
    k = len(comps)
    cimg = [comps.index(frozenset(perm[x] for x in C)) for C in comps]
    fixed = []
    for pt in set_partitions(range(k)):
        cp = frozenset(frozenset(B) for B in pt)
        if frozenset(frozenset(cimg[i] for i in B) for B in cp) == cp:
            fixed.append(cp)
    fixed.sort(key=lambda cp: len(cp))  # top (one block) first
    mu = {}
    for x in fixed:
        if len(x) == 1:
            mu[x] = 1
            continue
        s = 0
        for y, my in mu.items():
            if y != x and all(any(B <= C for C in y) for B in x):
                s += my
        mu[x] = -s
    total = 0
    for sig, m in mu.items():
        if m == 0:
            continue
        term = 1
        done = set()
        for B in sig:
            if B in done:
                continue
            pts = frozenset().union(*[comps[i] for i in B])
            orb = [pts]
            cur = pts
            while True:
                cur = frozenset(perm[x] for x in cur)
                if cur == pts:
                    break
                orb.append(cur)
            for Bb in sig:
                if frozenset().union(*[comps[i] for i in Bb]) in orb:
                    done.add(Bb)
            # the stabiliser of the block is <g^len(orb)>
            q = list(range(n))
            for _ in range(len(orb)):
                q = [perm[x] for x in q]
            if any(q[x] != x for x in pts):
                term = 0
                break
            term *= len(lin_ext(sorted(pts), [(a, b) for a, b in rel
                                              if a in pts and b in pts]))
        total += m * term
    return total


def _ev(n, i, j):
    v = [Fraction(0)] * n
    v[i], v[j] = Fraction(1), Fraction(-1)
    return v


