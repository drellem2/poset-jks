"""Checks for notes/fixed_point_formula.md.  Plain Python 3, exact arithmetic.

Self-contained: no imports from the other scripts in compute/.

For a reflection arrangement A (types A, B, D, H) with symmetry group G
(either W or the full group Aut generated by W and the extra generators
below), every top-cone V, and every g in Stab_G(V), put L = lin V and

  Lambda(V)   = supports (spans) of the faces of V, ordered by inclusion,
  chi_V(g)    = det(g) (-1)^d mu(Lambda(V)^g),
  LL^g        = the g-stable flats Y contained in L, ordered by inclusion,
  c(Y, g)     = number of chambers K of the localization A_Y with K in |V|
                and gK = K,
  chi_{V_Y}   = det(g | R^d/Y) (-1)^{codim Y} mu_{Lambda(V)^g}(Y, R^d).

Asserted checks (each on every (V, g), V up to W-conjugacy):
  [EZ]   #V^g = sum_{Y in LL^g} chi_{V_Y}(g)          (Theorem EZ).
  [CF]   chi_V(g) = sum_{Y in LL^g} mu_{LL^g}(0, Y) c(Y, g)   (Theorem CF).
  [VC]   if g != 1 and some hyperplane contains both L and Fix(g), then
         chi_V(g) = 0                                     (Corollary V).
  [WR]   if g != 1 and Fix(g) is a flat:
         sum_{Y in LL^g, Y cap Fix(g) = 0} mu_{Lambda^g}(Y, R^d) = 0  (Prop. W).
  [int]  the multiplicities of the trivial and det characters of Stab_W(V)
         in chi_V are nonnegative integers (chi_V is a character, Thm G*).
  [braid] for type A_{n-1}: mu(Lambda(C_P)^g) = mu(OP(P)^g), computed from
         order-preserving partitions; [Thm, eq. closed]
         sgn(g)(-1)^{n-3} mu(OP(P)^g) = mu(o) sum_{x in F(P,g)} e_C(P|B_0(x)),
         with e_C computed from rotation classes of words; and the poset form
         of [CF] (Corollary CF-braid), computed from Pi(components)^g and
         linear extensions only.
Reported (not asserted): whether [WR] also holds for elements of Aut whose
fixed space is not a flat; the conjugacy classes of W on which chi_V vanishes
for every cone.

Exit status 0 iff every asserted check passes.

Run from compute/:  python3 fixed_point_formula.py [--quick]
"""

