# Exact arithmetic in Q(sqrt 5)


class Q5:
    """a + b sqrt(5), a and b rational."""

    __slots__ = ("a", "b")

    def __init__(self, a, b=0):
        self.a = Fraction(a)
        self.b = Fraction(b)

    def _c(self, o):
        return o if isinstance(o, Q5) else Q5(o)

    def __add__(self, o):
        o = self._c(o)
        return Q5(self.a + o.a, self.b + o.b)

    __radd__ = __add__

    def __neg__(self):
        return Q5(-self.a, -self.b)

    def __sub__(self, o):
        return self + (-self._c(o))

    def __rsub__(self, o):
        return self._c(o) - self

    def __mul__(self, o):
        o = self._c(o)
        return Q5(self.a * o.a + 5 * self.b * o.b, self.a * o.b + self.b * o.a)

    __rmul__ = __mul__

    def __truediv__(self, o):
        o = self._c(o)
        n = o.a * o.a - 5 * o.b * o.b
        return self * Q5(o.a / n, -o.b / n)

    def __eq__(self, o):
        o = self._c(o)
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def sign(self):
        a, b = self.a, self.b
        if b == 0:
            return (a > 0) - (a < 0)
        if a == 0:
            return (b > 0) - (b < 0)
        if (a > 0) == (b > 0):
            return 1 if a > 0 else -1
        # opposite signs: compare a^2 with 5 b^2
        big_a = a * a > 5 * b * b
        return (1 if a > 0 else -1) if big_a else (1 if b > 0 else -1)

    def __repr__(self):
        return f"({self.a}+{self.b}r5)"


def sgn(x):
    if isinstance(x, Q5):
        return x.sign()
    return (x > 0) - (x < 0)


def is_zero(x):
    return sgn(x) == 0


def dot(u, v):
    return sum((a * b for a, b in zip(u, v)), Fraction(0) * 0)


def rank(rows):
    """Exact rank of a list of vectors."""
    m = [list(r) for r in rows]
    if not m:
        return 0
    ncol = len(m[0])
    r = 0
    for c in range(ncol):
        piv = next((i for i in range(r, len(m)) if not is_zero(m[i][c])), None)
        if piv is None:
            continue
        m[r], m[piv] = m[piv], m[r]
        p = m[r][c]
        m[r] = [x / p for x in m[r]]
        for i in range(len(m)):
            if i != r and not is_zero(m[i][c]):
                f = m[i][c]
                m[i] = [x - f * y for x, y in zip(m[i], m[r])]
        r += 1
        if r == len(m):
            break
    return r


def solve(A, b):
    """Solve A x = b (A square-or-tall with full column rank), exactly."""
    n = len(A[0])
    m = [list(A[i]) + [b[i]] for i in range(len(A))]
    r = 0
    piv_cols = []
    for c in range(n):
        piv = next((i for i in range(r, len(m)) if not is_zero(m[i][c])), None)
        if piv is None:
            continue
        m[r], m[piv] = m[piv], m[r]
        p = m[r][c]
        m[r] = [x / p for x in m[r]]
        for i in range(len(m)):
            if i != r and not is_zero(m[i][c]):
                f = m[i][c]
                m[i] = [x - f * y for x, y in zip(m[i], m[r])]
        piv_cols.append(c)
        r += 1
    assert len(piv_cols) == n, "singular system"
    for i in range(r, len(m)):
        assert is_zero(m[i][n]), "inconsistent system"
    x = [None] * n
    for i, c in enumerate(piv_cols):
        x[c] = m[i][n]
    return x


def det(M):
    n = len(M)
    m = [list(r) for r in M]
    d = Fraction(1)
    for c in range(n):
        piv = next((i for i in range(c, n) if not is_zero(m[i][c])), None)
        if piv is None:
            return Fraction(0)
        if piv != c:
            m[c], m[piv] = m[piv], m[c]
            d = -d
        p = m[c][c]
        d = d * p
        for i in range(c + 1, n):
            if not is_zero(m[i][c]):
                f = m[i][c] / p
                m[i] = [x - f * y for x, y in zip(m[i], m[c])]
    return d


def matmul(A, B):
    return [[sum((A[i][k] * B[k][j] for k in range(len(B))), Fraction(0) * 0)
             for j in range(len(B[0]))] for i in range(len(A))]


def matvec(A, v):
    return [sum((A[i][k] * v[k] for k in range(len(v))), Fraction(0) * 0)
            for i in range(len(A))]


def reflection(alpha):
    n = len(alpha)
    aa = dot(alpha, alpha)
    return [[(1 if i == j else 0) - 2 * alpha[i] * alpha[j] / aa
             for j in range(n)] for i in range(n)]


def key(v):
    return tuple(v)


