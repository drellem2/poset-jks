class Arr:
    def __init__(self, name, roots, extra, extra_gens):
        self.name = name
        self.extra = extra  # rows cutting out the essential space (type A)
        amb = len(roots[0])
        self.amb = amb
        self.d = amb - len(extra)
        # positive roots via a generic functional
        rho = [Fraction(3 ** k + k) for k in range(amb)][::-1]
        if isinstance(roots[0][0], Q5):
            rho = [Q5(x) for x in rho]
        pos = []
        for r in roots:
            s = sgn(dot(r, rho))
            assert s != 0, "rho not generic"
            if s > 0:
                pos.append(r)
        self.pos = pos
        self.N = N = len(pos)
        self.full = (1 << N) - 1
        self.rootkey = {}
        for i, r in enumerate(pos):
            self.rootkey[key(r)] = (i, 1)
            self.rootkey[key([-x for x in r])] = (i, -1)
        # simple roots: s_alpha sends exactly one positive root negative
        refl = [reflection(r) for r in pos]
        simple = []
        for i in range(N):
            neg = sum(1 for r in pos if self.rootkey[key(matvec(refl[i], r))][1] < 0)
            if neg == 1:
                simple.append(i)
        assert len(simple) == self.d, (name, len(simple))
        self.simple = simple
        # group generation (matrices + signed permutations of positive roots)
        gens_W = [refl[i] for i in simple]
        self.W = self._close(gens_W)
        gens_aut = gens_W + extra_gens
        self.Wset = {e["sp"] for e in self.W}
        if extra_gens:
            self.G = self._close(gens_aut)
            self.W = [e for e in self.G if e["sp"] in self.Wset]
        else:
            self.G = self.W
        # faces: orbit of faces of the fundamental chamber
        fund = []
        for J in itertools.product((0, 1), repeat=self.d):
            A = [pos[i] for i in simple] + list(extra)
            b = [Fraction(1 - J[k]) for k in range(self.d)] + [Fraction(0)] * len(extra)
            if isinstance(roots[0][0], Q5):
                A = [[x if isinstance(x, Q5) else Q5(x) for x in row] for row in A]
                b = [Q5(x) for x in b]
            x = solve(A, b)
            pm = nm = 0
            for i, r in enumerate(pos):
                s = sgn(dot(r, x))
                if s > 0:
                    pm |= 1 << i
                elif s < 0:
                    nm |= 1 << i
            fund.append((pm, nm))
        faces = set()
        for e in self.W:
            for (pm, nm) in fund:
                faces.add(self.act_face(e, pm, nm))
        self.faces = sorted(faces)
        self.chambers = sorted(pm for pm, nm in self.faces if pm | nm == self.full)
        assert len(self.chambers) == len(self.W)
        self.chidx = {c: i for i, c in enumerate(self.chambers)}
        # flats = zero sets of faces
        flats = sorted({self.full ^ (pm | nm) for pm, nm in self.faces})
        self.flats = flats
        self.rk = {}
        for Z in flats:
            rows = [pos[i] for i in range(N) if Z >> i & 1]
            self.rk[Z] = rank(rows)
        # chamber permutation per group element
        for e in self.G:
            e["chperm"] = [self.chidx[self.act_mask(e, c)] for c in self.chambers]
        # halfspaces
        self.half = []
        for i in range(N):
            plus = minus = 0
            for k, c in enumerate(self.chambers):
                if c >> i & 1:
                    plus |= 1 << k
                else:
                    minus |= 1 << k
            self.half.append((plus, minus))
        self._fixcache = {}

    # --- group elements -------------------------------------------------
    def _sp(self, M):
        perm, neg = [], 0
        for i, r in enumerate(self.pos):
            j, s = self.rootkey[key(matvec(M, r))]
            perm.append(j)
            if s < 0:
                neg |= 1 << i
        return tuple(perm), neg

    def _close(self, gens):
        amb = self.amb
        one = Q5(1) if isinstance(self.pos[0][0], Q5) else Fraction(1)
        zero = one * 0
        I = [[one if i == j else zero for j in range(amb)] for i in range(amb)]
        start = self._mk(I)
        seen = {start["sp"]: start}
        frontier = [start]
        gm = [(g, self._sp(g)) for g in gens]
        while frontier:
            nxt = []
            for e in frontier:
                for g, _ in gm:
                    M = matmul(g, e["M"])
                    sp = self._sp(M)
                    if sp not in seen:
                        f = self._mk(M, sp)
                        seen[sp] = f
                        nxt.append(f)
            frontier = nxt
        return list(seen.values())

    def _mk(self, M, sp=None):
        if sp is None:
            sp = self._sp(M)
        perm, neg = sp
        N = len(self.pos)
        t0 = [0] * 256
        t1 = [0] * 256
        t2 = [0] * 256
        for b in range(256):
            for k in range(8):
                if b >> k & 1:
                    if k < N:
                        t0[b] |= 1 << perm[k]
                    if 8 + k < N:
                        t1[b] |= 1 << perm[8 + k]
                    if 16 + k < N:
                        t2[b] |= 1 << perm[16 + k]
        dM = det(M)
        if self.extra:  # type A: divide out the eigenvalue on (1,...,1)
            v = matvec(M, self.extra[0])
            c = v[0] / self.extra[0][0]
            dM = dM / c
        d = sgn(dM)
        assert dM == d
        return {"M": M, "sp": sp, "neg": neg, "t": (t0, t1, t2), "det": d,
                "id": all(perm[i] == i for i in range(N)) and neg == 0}

    @staticmethod
    def pmask(e, m):
        t0, t1, t2 = e["t"]
        return t0[m & 255] | t1[(m >> 8) & 255] | t2[(m >> 16) & 255]

    def act_mask(self, e, pm):
        """Image of the chamber with positive set pm."""
        return self.pmask(e, pm ^ e["neg"])

    def act_face(self, e, pm, nm):
        ng = e["neg"]
        return (self.pmask(e, (pm & ~ng) | (nm & ng)),
                self.pmask(e, (nm & ~ng) | (pm & ng)))

    def act_restricted(self, e, p, Z):
        """Image of the chamber of A_Z with positive set p (subset of Z)."""
        return self.pmask(e, (p ^ e["neg"]) & Z)

    # --- linear algebra on flats ---------------------------------------
    def fixrows(self, e):
        M = e["M"]
        return [[M[i][j] - (1 if i == j else 0) for j in range(self.amb)]
                for i in range(self.amb)]

    def dim_fix_in(self, e, Z):
        """dim (Y cap Fix g) for the flat Y with zero set Z."""
        k = (e["sp"], Z)
        if k not in self._fixcache:
            rows = [self.pos[i] for i in range(self.N) if Z >> i & 1]
            rows += self.fixrows(e) + list(self.extra)
            self._fixcache[k] = self.amb - rank(rows)
        return self._fixcache[k]

    def fix_is_flat(self, e):
        """Is Fix(g) (in the essential space) an intersection of hyperplanes?"""
        base = self.fixrows(e) + list(self.extra)
        rb = rank(base)
        Z = 0
        for i, r in enumerate(self.pos):
            if rank(base + [r]) == rb:
                Z |= 1 << i
        dimfix = self.amb - rb
        rZ = rank([self.pos[i] for i in range(self.N) if Z >> i & 1]) if Z else 0
        return self.d - rZ == dimfix, Z


