def roots_A(n):
    """A_n in R^{n+1}; extra row (1,...,1) cuts out the essential space."""
    N = n + 1
    R = []
    for i in range(N):
        for j in range(N):
            if i != j:
                v = [Fraction(0)] * N
                v[i], v[j] = Fraction(1), Fraction(-1)
                R.append(v)
    return R, [[Fraction(1)] * N]


def roots_B(n):
    R = []
    for i in range(n):
        for s in (1, -1):
            v = [Fraction(0)] * n
            v[i] = Fraction(s)
            R.append(v)
    for i, j in itertools.combinations(range(n), 2):
        for s, t in itertools.product((1, -1), repeat=2):
            v = [Fraction(0)] * n
            v[i], v[j] = Fraction(s), Fraction(t)
            R.append(v)
    return R, []


def roots_D(n):
    R = []
    for i, j in itertools.combinations(range(n), 2):
        for s, t in itertools.product((1, -1), repeat=2):
            v = [Fraction(0)] * n
            v[i], v[j] = Fraction(s), Fraction(t)
            R.append(v)
    return R, []


def roots_H3():
    tau = Q5(Fraction(1, 2), Fraction(1, 2))
    itau = Q5(Fraction(-1, 2), Fraction(1, 2))
    half = Fraction(1, 2)
    R = []
    for i in range(3):
        for s in (1, -1):
            v = [Q5(0)] * 3
            v[i] = Q5(s)
            R.append(v)
    base = [tau, Q5(1), itau]
    for shift in range(3):  # even (cyclic) permutations
        coords = [base[(k + shift) % 3] for k in range(3)]
        for signs in itertools.product((1, -1), repeat=3):
            R.append([coords[k] * signs[k] * half for k in range(3)])
    assert len(R) == 30
    return R, []


def f4_short():
    """Extra reflections generating W(F4) ⊇ W(D4): triality etc."""
    out = []
    for i in range(4):
        v = [Fraction(0)] * 4
        v[i] = Fraction(1)
        out.append(v)
    out.append([Fraction(1, 2)] * 4)
    return out


