def all_cones(arr):
    allc = (1 << len(arr.chambers)) - 1
    seen = {allc}
    stack = [allc]
    while stack:
        V = stack.pop()
        for plus, minus in arr.half:
            for h in (plus, minus):
                U = V & h
                if U and U not in seen:
                    seen.add(U)
                    stack.append(U)
    return seen


def bits(m):
    out = []
    while m:
        low = m & -m
        out.append(low.bit_length() - 1)
        m ^= low
    return out


def image(chperm, V):
    out = 0
    for i in bits(V):
        out |= 1 << chperm[i]
    return out


def orbit_reps(arr, cones):
    reps = []
    seen = set()
    for V in sorted(cones):
        if V in seen:
            continue
        orb = {image(e["chperm"], V) for e in arr.W}
        seen |= orb
        reps.append((V, len(orb)))
    return reps


def cone_data(arr, V):
    ch = [arr.chambers[i] for i in bits(V)]
    andp = arr.full
    orp = 0
    for c in ch:
        andp &= c
        orp |= c
    splus = andp           # hyperplanes with V on the + side
    sminus = arr.full ^ orp
    smax = splus | sminus
    lam = sorted({arr.full ^ (pm | nm) for pm, nm in arr.faces
                  if not (nm & splus) and not (pm & sminus)})
    return ch, smax, lam


def mu_to_top(elems):
    """mu(x, top) for x in a poset of zero-set masks ordered by reverse
    inclusion (top = smallest zero set, here required to be 0)."""
    order = sorted(elems, key=lambda Z: bin(Z).count("1"))
    mu = {}
    for x in order:
        if x == 0:
            mu[x] = 1
            continue
        s = 0
        for y, my in mu.items():
            if y != x and (y & ~x) == 0:
                s += my
        mu[x] = -s
    return mu


def mu_from_bottom(elems, bottom):
    """mu(bottom, y) in the same order (bottom = largest zero set)."""
    order = sorted(elems, key=lambda Z: -bin(Z).count("1"))
    mu = {}
    for y in order:
        if y == bottom:
            mu[y] = 1
            continue
        s = 0
        for x, mx in mu.items():
            if x != y and (y & ~x) == 0:
                s += mx
        mu[y] = -s
    return mu


def analyse(arr, V, smax, ch, lam, e, stats):
    """All checks for one (V, g).  Returns chi_V(g)."""
    d = arr.d
    pm = lambda Z: arr.pmask(e, Z)
    lamg = [Z for Z in lam if pm(Z) == Z]
    mut = mu_to_top(lamg)
    chi = e["det"] * (-1) ** d * mut[arr.full]
    LL = [Z for Z in lamg if Z & smax == smax]
    # [EZ]
    nfix = sum(1 for c in ch if arr.act_mask(e, c) == c)
    ez = 0
    for Z in LL:
        dimY = d - arr.rk[Z]
        dimYg = arr.dim_fix_in(e, Z)
        detY = (-1) ** (dimY - dimYg)
        detbar = e["det"] * detY
        ez += detbar * (-1) ** arr.rk[Z] * mut[Z]
    stats["EZ"][ez == nfix] += 1
    # [CF]
    mub = mu_from_bottom(LL, arr.full)
    cf = 0
    for Z in LL:
        if mub[Z] == 0:
            continue
        ks = {c & Z for c in ch}
        cnt = sum(1 for p in ks if arr.act_restricted(e, p, Z) == p)
        cf += mub[Z] * cnt
    stats["CF"][cf == chi] += 1
    # [VC] vanishing criterion: a hyperplane contains both L and Fix(g)
    if not e["id"]:
        _, zg = arr.fix_is_flat_cached(e)
        ZL = min(LL, key=lambda Z: bin(Z).count("1"))  # zero set of L itself
        crit = (ZL & zg) != 0
        if crit:
            stats["VC"][chi == 0] += 1
        key_ = "nz" if chi != 0 else ("z-crit" if crit else "z-other")
        stats.setdefault("cnt", defaultdict(int))
        stats["cnt"][key_] += 1
    # [WR]
    if not e["id"]:
        flat, _ = arr.fix_is_flat_cached(e)
        s = sum(mut[Z] for Z in LL if arr.dim_fix_in(e, Z) == 0)
        if flat:
            stats["WR"][s == 0] += 1
        else:
            stats["WR-nonflat"][s == 0] += 1
    return chi, nfix


