def charpoly_key(arr, e):
    """Conjugacy invariant: dims of the fixed spaces of g^k, k = 1..order
    (the characteristic polynomial up to Galois conjugacy)."""
    M = e["M"]
    k = 1
    P = M
    dims = []
    while True:
        rows = [[P[i][j] - (1 if i == j else 0) for j in range(arr.amb)]
                for i in range(arr.amb)] + list(arr.extra)
        dims.append(arr.amb - rank(rows))
        if dims[-1] == arr.d:
            break
        P = matmul(M, P)
        k += 1
    return tuple(dims)


