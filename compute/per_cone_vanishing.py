def part_TAarr(quick):
    print("[TAarr] Theorem TA against chi_V(g) from the face poset of the braid arrangement")
    ok = True
    for n in ([4] if quick else [4, 5]):
        arr, G, W = A2.typeA(n)
        d = n - 1

        def coords(i):
            return [int(k == i) for k in range(d)] if i < d else [0] * d
        neg = {}
        for w in itertools.permutations(range(n)):
            cols = [[-(a - b) for a, b in zip(coords(w[i]), coords(w[n - 1]))] for i in range(d)]
            M = tuple(tuple(Fr(cols[j][i]) for j in range(d)) for i in range(d))
            neg[M] = w
        pairsAB = [(i, j) for i, j in itertools.combinations(range(n), 2)]
        cnt = nz = 0
        for mask in arr.top_cones():
            S = arr.cone_constraints(mask)
            # constraint s*(x_i - x_j) >= 0 : s = +1 means j <= i
            rel = set()
            for e, s in S.items():
                i, j = pairsAB[e]
                rel.add((j, i) if s > 0 else (i, j))
            rel = frozenset(rel)
            for g in G:
                if g.M not in neg or g.act_mask(mask) != mask:
                    continue
                w = neg[g.M]
                c1 = A2.chi_def(arr, S, g)
                c2 = chi_closed(n, rel, w)
                cnt += 1
                nz += c1 != 0
                if c1 != c2:
                    ok = False
                    print(f"    FAIL A{n-1} P={sorted(rel)} w={w} chi={c1} closed={c2}")
        print(f"  A{n-1}: {cnt} pairs (V, -w) (every cone, every -w in Stab(V)), {nz} nonzero, "
              f"closed formula agrees on all: {ok}")
    return ok


