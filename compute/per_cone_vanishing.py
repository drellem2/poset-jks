def mobius_up(elems, leq, start):
    """mu(start, x) for x >= start."""
    up0 = [x for x in elems if leq(start, x)]
    up = sorted(up0, key=lambda x: sum(1 for y in up0 if leq(y, x)))
    mu = {}
    for x in up:
        mu[x] = 1 if x == start else -sum(mu[y] for y in mu if y != x and leq(y, x))
    return mu


def part_M_and_CRV(quick):
    ok = True
    print("[M] Lemma M on all chambers; Crapo: complements of U in L(A)^g = Z*(g) when U is a flat")
    print("[CRV] per pair (V, g): mu(Lambda(V)^g) = 0 iff Lambda(V)^g has an uncomplemented element")
    print("  arrangement | pairs | chi != 0 | Cor.V zeros | 'no nonzero mu' zeros | cancelling | "
          "CR_V holds | (lin V, g) keys with mixed vanishing | classes with both signs | "
          "Lemma M terms | classes with U a flat (Crapo = Z*)")
    rows = []
    for name, bld in builders(quick):
        arr, G, W = bld()
        cones = arr.top_cones()
        top = frozenset()
        st = dict(pairs=0, nz=0, corV=0, empty=0, canc=0, crv_ok=True, mixed=0, bothsign=0,
                  M=0, flatU=0)
        for cl in A2.conj_classes(G):
            g = cl[0]
            gd = A2.GData(arr, g)
            U = gd.U
            # Lemma M
            for X in gd.Zstar:
                rhs = 0
                for Z in gd.stable:
                    if arr.leq(X, Z):
                        BZ = arr.basis(Z)
                        if len(BZ) + len(U) - (A2.rank(BZ + U) if BZ + U else 0) == 0:
                            rhs += mobius_up(gd.stable, arr.leq, Z)[top]
                lhs = gd.m_X(X, {})
                st['M'] += 1
                if lhs != (-1) ** len(U) * rhs:
                    ok = False
                    print(f"    FAIL Lemma M {name}")
            # Crapo when U is a flat
            Uflat = [Y for Y in arr.flats if arr.flat_dim[Y] == len(U)
                     and all(sum(a * b for a, b in zip(arr.normals[e], u)) == 0 for e in Y for u in U)]
            if Uflat:
                u = Uflat[0]
                st['flatU'] += 1
                comp = []
                for X in gd.stable:
                    meet = X | u
                    joins = [Y for Y in gd.stable if arr.leq(X, Y) and arr.leq(u, Y)]
                    join = [Y for Y in joins if all(arr.leq(Y, Z) for Z in joins)][0]
                    if arr.closure(meet) == arr.bottom and join == top:
                        comp.append(X)
                if set(comp) != set(gd.Zstar):
                    ok = False
                    print(f"    FAIL Crapo complements != Z* in {name}")
            byL, signs = {}, set()
            for mask in cones:
                if g.act_mask(mask) != mask:
                    continue
                S = arr.cone_constraints(mask)
                L = arr.lin(S)
                Lam = [X for X in arr.Lambda(S) if g.stable_flat(X)]
                mu, unc = lattice_info(Lam, arr.leq)
                chi = (-1) ** arr.d * g.det * mu
                st['pairs'] += 1
                byL.setdefault(L, set()).add(chi != 0)
                if chi:
                    st['nz'] += 1
                    signs.add(chi > 0)
                else:
                    corV = any(e in L and all(sum(a * b for a, b in zip(arr.normals[e], v)) == 0 for v in U)
                               for e in range(arr.n))
                    zs = [X for X in gd.Zstar if arr.leq(X, L) and gd.mu0[X]]
                    if corV:
                        st['corV'] += 1
                    elif not zs:
                        st['empty'] += 1
                    else:
                        st['canc'] += 1
                if (mu == 0) != unc:
                    st['crv_ok'] = False
                    ok = False
                    print(f"    CR_V FAILS {name} g={g.M} S={S}")
            st['mixed'] += sum(1 for v in byL.values() if len(v) > 1)
            st['bothsign'] += len(signs) > 1
        rows.append((name, st))
        print(f"  {name} | {st['pairs']} | {st['nz']} | {st['corV']} | {st['empty']} | {st['canc']} | "
              f"{st['crv_ok']} | {st['mixed']} | {st['bothsign']} | {st['M']} | {st['flatU']}", flush=True)
    return ok


def part_coxeter(quick):
    print("[CRV-Cox] W-orbit representatives V x classes of Stab_G(V) (convention of "
          "vanishing_criterion.py), F_4 sampled (all chambers + 12 cones per class, seed 1)")
    print("  type | pairs | chi != 0 | Cor.V zeros | 'no nonzero mu' zeros | cancelling | CR_V holds")
    ok = True
    for name in (["B4", "D4", "H3"] if quick else ["B4", "D4", "H3", "F4"]):
        A = VCm.Arrangement(name)
        Gcl = VCm.classes_in(A.G)
        if name == "F4":
            pairs = [(V, g) for V, g, _ in VCm.sample_pairs(A, Gcl, 12, 1)]
        else:
            pairs = []
            for V in VCm.orbit_reps(A, VCm.all_cones(A), A.W):
                P, N = VCm.cone_constraints(A, V)
                for g, _ in VCm.classes_in(VCm.stabilizer(A, P, N)):
                    pairs.append((V, g))
        gctx = {}
        st = dict(pairs=0, nz=0, corV=0, empty=0, canc=0)
        crv = True
        for V, g in pairs:
            if g not in gctx:
                gctx[g] = VCm.GCtx(A, g)
            Gc = gctx[g]
            C = VCm.ConeCtx(A, V)
            lamg = [Z for Z in C.lam if A.act_mask(g, Z) == Z]
            mu, unc = lattice_info(lamg, lambda a, b: (a & b) == b)
            chi = (-1) ** A.d * Gc.gd["det"] * mu
            assert chi == VCm.chi_direct(C, g, Gc.gd)
            st['pairs'] += 1
            if chi:
                st['nz'] += 1
            elif C.Lhyp & Gc.gd["hypU"]:
                st['corV'] += 1
            elif not any(m_ and (X & C.Lhyp) == C.Lhyp for X, m_ in Gc.zmu.items()):
                st['empty'] += 1
            else:
                st['canc'] += 1
            if (mu == 0) != unc:
                crv = ok = False
                print(f"    CR_V FAILS {name}")
        print(f"  {name} | {st['pairs']} | {st['nz']} | {st['corV']} | {st['empty']} | {st['canc']} | {crv}",
              flush=True)
    return ok


